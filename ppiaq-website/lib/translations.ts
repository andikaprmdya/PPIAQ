export function getTranslation(
  obj: unknown,
  lang: Language = 'en'
): string {
  if (typeof obj === 'string') {
    return obj;
  }

  if (
    obj &&
    typeof obj === 'object' &&
    'id' in obj &&
    'en' in obj
  ) {
    const value = obj as Record<Language, string>;
    return value[lang] ?? value.en ?? value.id ?? '';
  }

  return '';
}

export function getTranslationByKey(
  key: string,
  lang: Language,
  fallback = ''
): string {
  const parts = key.split('.');
  let current: unknown = translations;

  for (const part of parts) {
    if (!current || typeof current !== 'object' || !(part in (current as Record<string, unknown>))) {
      return fallback;
    }
    current = (current as Record<string, unknown>)[part];
  }

  const value = getTranslation(current, lang);
  return value || fallback;
}

export function createTranslator(lang: Language) {
  return (key: string, fallback = '') => getTranslationByKey(key, lang, fallback);
}
