import { createHash } from 'node:crypto';
import { mkdir, stat, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = fileURLToPath(new URL('../', import.meta.url));
const destination = join(root, 'public/images/optimized');
await mkdir(destination, { recursive: true });
const photos = [];
const widths = [480, 960, 1200, 1600];
let originalBytes = 0;
let generatedBytes = 0;

for (const [index, extension] of ['jpg', 'jpeg', 'jpg', 'jpg'].entries()) {
  const name = `home-shuffle-${index + 1}`;
  const source = join(root, 'public/images', `${name}.${extension}`);
  originalBytes += (await stat(source)).size;
  const variants = [];
  for (const width of widths) {
    // The carousel already displays a centered 16:7 crop. Prepare that exact
    // crop once, rather than sending invisible pixels or transforming at runtime.
    const data = await sharp(source).rotate()
      .resize(width, width * 7 / 16, { fit: 'cover' })
      .webp({ quality: 76, effort: 6 }).toBuffer();
    const hash = createHash('sha256').update(data).digest('hex').slice(0, 12);
    const filename = `${name}-${width}-${hash}.webp`;
    await writeFile(join(destination, filename), data);
    variants.push({ src: `/images/optimized/${filename}`, width });
    generatedBytes += data.length;
  }
  photos.push({
    src: variants[1].src,
    srcSet: variants.map(({ src, width }) => `${src} ${width}w`).join(', '),
    width: 1600,
    height: 700,
  });
}

const manifest = join(root, 'lib/home-gallery.generated.ts');
await mkdir(dirname(manifest), { recursive: true });
await writeFile(manifest,
  '// Generated by npm run images:optimize. Filenames contain a content hash.\n' +
  `export const HOME_GALLERY = ${JSON.stringify(photos, null, 2)} as const;\n`);
console.log(JSON.stringify({ photos: photos.length, variants: photos.length * widths.length, originalBytes, generatedBytes }));
